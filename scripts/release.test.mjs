import { test } from 'node:test'
import assert from 'node:assert/strict'
import { validateManifest, publicationOrder, auditPackedFiles, requiredTags } from './release-contract.mjs'

const core = { name: '@alneas/eaos-core', version: '0.4.4', license: 'MIT', type: 'module', engines: { node: '>=24.0.0' }, publishConfig: { registry: 'https://registry.npmjs.org', access: 'public' }, files: ['dist', 'README.md', 'LICENSE', 'CHANGELOG.md'], exports: { '.': { types: './dist/index.d.ts', import: './dist/index.js' } } }
const files = ['package.json','README.md','LICENSE','CHANGELOG.md','dist/index.js','dist/index.d.ts'].map(path => ({ path, content: '' }))
test('rejects restricted dependencies, unpublished links and unsupported Appkit versions in every dependency field', () => {
  for (const field of ['dependencies','peerDependencies','optionalDependencies','devDependencies']) {
    for (const [name, value] of [['@dataarthub/app-core','1.4.1'],['other','file:../private'],['@alneas/appkit-core','^0.2.0']]) {
      assert.ok(validateManifest({ ...core, [field]: { [name]: value } }).length, `${field}:${name}`)
    }
  }
  assert.deepEqual(validateManifest({ ...core, dependencies: { '@alneas/appkit-core': '0.2.0' } }), [])
})
test('orders runtime and peer prerequisites and rejects missing/incompatible internal versions and cycles', () => {
  const server = { ...core, name: '@alneas/eaos-server', dependencies: { [core.name]: '^0.4.4' } }
  const ui = { ...core, name: '@alneas/eaos-react', peerDependencies: { [server.name]: '^0.4.4' } }
  assert.deepEqual(publicationOrder([ui,server,core]).map(x=>x.name), [core.name,server.name,ui.name])
  assert.throws(()=>publicationOrder([server]), /Missing/)
  assert.throws(()=>publicationOrder([core,{ ...server, dependencies: { [core.name]: '^1.0.0' } }]), /Incompatible/)
  assert.throws(()=>publicationOrder([{ ...core, dependencies: { [server.name]: '^0.4.4' } },server]), /cycle/)
})
test('audits actual payload: export presence, required history and forbidden files/content', () => {
  assert.deepEqual(auditPackedFiles(core,files), [])
  assert.deepEqual(auditPackedFiles(core,files.map(f=>f.path==='dist/index.js'?{...f,content:'const containerSchema = `file:///etc/config/kratos/identity.json`'}:f)), [])
  for (const removed of ['CHANGELOG.md','dist/index.d.ts']) assert.ok(auditPackedFiles(core,files.filter(f=>f.path!==removed)).length)
  for (const path of ['node_modules/pkg/index.js','.verification/logs/run.json','dist/secret.test.js','dist/.env','../escape','src/implementation.ts']) assert.ok(auditPackedFiles(core,[...files,{path,content:''}]).length,path)
  assert.ok(auditPackedFiles(core,files.map(f=>f.path==='dist/index.js'?{...f,content:'import x from "@dataarthub/app-core"'}:f)).length)
  assert.ok(auditPackedFiles(core,files.map(f=>f.path==='dist/index.js'?{...f,content:'const source = "/Users/operator/private/source"'}:f)).length)
})
test('pre-1.0 and prerelease channels follow the shared completion contract', () => {
  assert.deepEqual(requiredTags('0.4.4'), ['beta','latest'])
  assert.deepEqual(requiredTags('1.0.0-beta.1'), ['beta','latest'])
  assert.deepEqual(requiredTags('1.0.0'), ['latest'])
  assert.throws(()=>requiredTags('garbage'), /version/)
})

test('source identity includes scripts and lockfile, ignores outputs and rejects source symlinks', async () => {
  const { mkdtemp,writeFile,mkdir,rm,symlink } = await import('node:fs/promises')
  const { tmpdir } = await import('node:os')
  const { join } = await import('node:path')
  const { sourceHash, cleanCommit } = await import('./source-state.mjs')
  const dir=await mkdtemp(join(tmpdir(),'eaos-source-test-'))
  try {
    await writeFile(join(dir,'bun.lock'),'first')
    const before=await sourceHash(dir)
    await mkdir(join(dir,'dist'));await writeFile(join(dir,'dist/output.js'),'generated')
    assert.equal(await sourceHash(dir),before)
    assert.notEqual(await sourceHash(dir,new Set()),before,'Built-output identity includes generated bytes')
    await writeFile(join(dir,'bun.lock'),'second');assert.notEqual(await sourceHash(dir),before)
    await symlink(join(dir,'bun.lock'),join(dir,'linked.ts'))
    await assert.rejects(()=>sourceHash(dir),/symlink/)
    assert.throws(()=>cleanCommit(dir),/clean source commit/)
  } finally { await rm(dir,{recursive:true,force:true}) }
})

test('commit-bound verification refuses an amended commit or absent/mismatched consumer evidence', async () => {
  const { verifyCandidateIdentity } = await import('./release-contract.mjs')
  const archives=[{name:core.name,version:core.version,sha256:'bytes'}]
  const bundle={state:'commit-bound',commit:'source-commit',sourceHash:'source',archives,consumerVerified:{sourceHash:'source',archives}}
  assert.doesNotThrow(()=>verifyCandidateIdentity(bundle,{sourceHash:'source',cleanCommit:'source-commit'}))
  assert.throws(()=>verifyCandidateIdentity(bundle,{sourceHash:'source',cleanCommit:'amended'}),/commit/)
  assert.throws(()=>verifyCandidateIdentity({...bundle,consumerVerified:false},{sourceHash:'source',cleanCommit:'source-commit'}),/consumer/)
  assert.throws(()=>verifyCandidateIdentity({...bundle,consumerVerified:{sourceHash:'other',archives}},{sourceHash:'source',cleanCommit:'source-commit'}),/consumer/)
  assert.throws(()=>verifyCandidateIdentity({...bundle,consumerVerified:{sourceHash:'source',archives:[]}},{sourceHash:'source',cleanCommit:'source-commit'}),/consumer/)
})

test('Appkit pins follow each package version and reject unsupported exact pins', () => {
  for (const [name, version, rejected] of [['@alneas/appkit-core', '0.2.0', '0.2.1'], ['@alneas/appkit-react', '0.3.0', '0.2.0']]) {
    assert.deepEqual(validateManifest({ ...core, peerDependencies: { [name]: version } }), [])
    assert.ok(validateManifest({ ...core, peerDependencies: { [name]: rejected } }).length)
  }
})
