import { createHash, randomBytes, randomUUID, timingSafeEqual } from 'node:crypto'
import type { AuditSink } from './audit-sink'

/**
 * Host-verified tenant/user identity with role and optional API scope claims.
 * @see {@link issueApiKey}
 */
export interface PlatformPrincipal {
  
/** User identity within the tenant supplied by the trusted host. */
  userId: string
  
/** Verified tenant boundary for the record or operation; host authorization must establish this scope. */
  tenantId: string
  
/** Role claims supplied by the host after identity verification. */
  roles: readonly string[]
  
/** Exact API permission scope names associated with the verified identity/key. */
  scopes?: readonly string[]
}

/**
 * Validate the required shape of a host-verified principal.
 * @param value - Nonblank user/tenant IDs and nonblank role/scope entries; roles may be empty.
 * @returns No value; completion confirms shape only.
 * @throws Error when the principal shape is invalid.
 * @remarks Does not authenticate a user or authorize operations; the host must establish principal trust.
 * @example
 * ```typescript
 * import { assertPlatformPrincipal } from "@alneas/eaos-core/security/platform-security";
 * assertPlatformPrincipal({ userId: "user-demo", tenantId: "tenant-demo", roles: ["member"] });
 * ```
 */
export function assertPlatformPrincipal(value: PlatformPrincipal): void {
  if (!value || typeof value.userId !== 'string' || !value.userId.trim() || typeof value.tenantId !== 'string' || !value.tenantId.trim() || !Array.isArray(value.roles) || value.roles.some(role => typeof role !== 'string' || !role.trim()) || (value.scopes !== undefined && (!Array.isArray(value.scopes) || value.scopes.some(scope => typeof scope !== 'string' || !scope.trim())))) throw new Error('Verified platform principal required')
}

/**
 * Hash-only API key metadata suitable for host persistence and revocation checks.
 * @see {@link issueApiKey}
 */
export interface ApiKeyRecord {
  
  /** Key-record identity used by host persistence; defaults to a random UUID at issuance. */
  id: string
  
  /** API mount path or public API-key lookup prefix; neither value grants authorization. */
  prefix: string
  
  /** Content integrity digest; hashes are unkeyed and do not establish authorization or writer authenticity. */
  hash: string
  
/** Verified tenant boundary for the record or operation; host authorization must establish this scope. */
  tenantId: string
  
/** User identity within the tenant supplied by the trusted host. */
  userId: string
  
/** Exact API permission scope names associated with the verified identity/key. */
  scopes: readonly string[]
  
/** Creation timestamp supplied or generated by the owning API. */
  createdAt: string
  
/** Optional absolute expiry; the owning validation/evaluation API determines whether it remains live. */
  expiresAt?: string | null
  
/** Revocation timestamp when present; an active value disables use. */
  revokedAt?: string | null
}

/**
 * One-time secret paired with its hash-only storage record.
 * @see {@link issueApiKey}
 */
export interface IssuedApiKey { 
  /** Shared or one-time secret value; keep it out of persistence/logs except through host-approved secret storage. */
  secret: string; 
  /** API-key hash-only metadata suitable for host persistence; it excludes the returned one-time secret. */
  record: ApiKeyRecord }

function digest(value: string): string { return createHash('sha256').update(value, 'utf8').digest('hex') }

function validFutureDate(value: string | null | undefined, now: Date): boolean {
  return value === undefined || value === null || (Number.isFinite(Date.parse(value)) && Date.parse(value) > now.getTime())
}

/**
 * Generate a secret once; only the digest is suitable for persistence.
 * @param input - Tenant/user IDs and nonempty scopes; optional ID defaults to randomUUID, now to current Date, and expiry must be absent/null or strictly after now.
 * @returns The secret and record. Persist only record; return the secret to its owner through a protected channel.
 * @throws Error for blank identity/scopes or nonfuture expiry; date/crypto failures propagate.
 * @remarks Requires node:crypto. Does not persist or authorize key issuance; the host must protect the secret and enforce tenant/key policy.
 * @example
 * ```typescript
 * import { issueApiKey } from "@alneas/eaos-core/security/platform-security";
 * const issued = issueApiKey({ tenantId: "tenant-demo", userId: "user-demo", scopes: ["notes:read"] });
 * console.log(issued.record.prefix);
 * ```
 */
export function issueApiKey(input: { 
  /**
   * Nonblank host-verified tenant identity bound to the generated key record; this function does not authorize key issuance.
   */
  tenantId: string; 
  /**
   * Nonblank verified key owner identity copied into the persistence record.
   */
  userId: string; 
  /**
   * Nonempty exact permission-scope names; every entry must be nonblank. Verification later matches a requested scope exactly.
   */
  scopes: readonly string[]; 
  /**
   * Optional host key-record identity; omission generates a random UUID, without checking external uniqueness.
   */
  id?: string; 
  /**
   * Optional issuance clock used for createdAt and expiry comparison; omission uses a new current Date.
   */
  now?: Date; 
  /**
   * Optional parseable absolute expiry strictly after now; null or omission means no expiry is recorded.
   */
  expiresAt?: string | null }): IssuedApiKey {
  const now = input.now ?? new Date()
  if (!input.tenantId.trim() || !input.userId.trim() || !input.scopes.length || input.scopes.some(scope => !scope.trim()) || !validFutureDate(input.expiresAt, now)) throw new Error('Invalid API key issuance input')
  const token = randomBytes(32).toString('base64url')
  const prefix = token.slice(0, 12)
  const secret = `eaos_${prefix}_${token}`
  return { secret, record: { id: input.id ?? randomUUID(), prefix, hash: digest(secret), tenantId: input.tenantId, userId: input.userId, scopes: Object.freeze([...input.scopes]), createdAt: now.toISOString(), ...(input.expiresAt === undefined ? {} : { expiresAt: input.expiresAt }), revokedAt: null } }
}

/**
 * Check whether a key is unrevoked and not expired.
 * @param record - Stored key lifecycle metadata; this helper does not validate all record fields.
 * @param now - Evaluation clock; defaults to current Date.
 * @returns True when revokedAt is falsy and expiry is absent/falsy or a parseable future instant.
 * @example
 * ```typescript
 * import { isApiKeyActive } from "@alneas/eaos-core/security/platform-security";
 * import { issueApiKey } from "@alneas/eaos-core/security/platform-security";
 * const issued = issueApiKey({ tenantId: "tenant-demo", userId: "user-demo", scopes: ["notes:read"] });
 * console.log(isApiKeyActive(issued.record)); // true
 * ```
 */
export function isApiKeyActive(record: ApiKeyRecord, now = new Date()): boolean {
  return !record.revokedAt && (!record.expiresAt || (Number.isFinite(Date.parse(record.expiresAt)) && Date.parse(record.expiresAt) > now.getTime()))
}

/**
 * Compare an API secret against an active stored digest and optional scope.
 * @param secret - Presented eaos_ secret.
 * @param record - Trusted stored record selected by the host.
 * @param requiredScope - Exact scope required when supplied; omission skips scope checking.
 * @param now - Evaluation clock; defaults to current Date.
 * @returns Whether prefix, active lifecycle, constant-time digest comparison and optional exact scope match.
 * @remarks Requires node:crypto. The caller must select the record within the correct tenant and enforce any additional authorization.
 * @example
 * ```typescript
 * import { verifyApiKey } from "@alneas/eaos-core/security/platform-security";
 * import { issueApiKey } from "@alneas/eaos-core/security/platform-security";
 * const issued = issueApiKey({ tenantId: "tenant-demo", userId: "user-demo", scopes: ["notes:read"] });
 * console.log(verifyApiKey(issued.secret, issued.record, "notes:read")); // true
 * ```
 */
export function verifyApiKey(secret: string, record: ApiKeyRecord, requiredScope?: string, now = new Date()): boolean {
  if (typeof secret !== 'string' || !secret.startsWith(`eaos_${record.prefix}_`) || !isApiKeyActive(record, now)) return false
  const actual = Buffer.from(digest(secret), 'hex'), expected = Buffer.from(record.hash, 'hex')
  if (actual.length !== expected.length || !timingSafeEqual(actual, expected)) return false
  return requiredScope === undefined || record.scopes.includes(requiredScope)
}

/**
 * Create a revoked copy of an API key record.
 * @param record - Stored key; an existing revokedAt is retained.
 * @param now - Revocation time when not already revoked; defaults to current Date.
 * @returns A cloned record carrying revokedAt; caller must persist it.
 * @throws Native cloning errors or RangeError for an invalid Date when creating a revocation timestamp.
 * @example
 * ```typescript
 * import { revokeApiKey } from "@alneas/eaos-core/security/platform-security";
 * import { issueApiKey } from "@alneas/eaos-core/security/platform-security";
 * const issued = issueApiKey({ tenantId: "tenant-demo", userId: "user-demo", scopes: ["notes:read"] });
 * console.log(revokeApiKey(issued.record).revokedAt);
 * ```
 */
export function revokeApiKey(record: ApiKeyRecord, now = new Date()): ApiKeyRecord {
  if (record.revokedAt) return structuredClone(record)
  return { ...structuredClone(record), revokedAt: now.toISOString() }
}

/**
 * Caller-supplied audit scope, action, outcome and optional resource context.
 * @see {@link issueApiKey}
 */
export interface PlatformAuditEventInput {
  
/** Verified tenant boundary for the record or operation; host authorization must establish this scope. */
  tenantId: string
  
/** User identity within the tenant supplied by the trusted host. */
  userId: string
  
  /** Named host action performed or requested; procedure exception entries use this as the response instruction. */
  action: string
  
  /** Reported success/failure/denial/unknown category; reconcile uncertain effects before retrying. */
  outcome: 'success' | 'denied' | 'failure'
  
/** Optional audit resource category. */
  resourceType?: string
  
/** Optional audit resource identity. */
  resourceId?: string
  
/** Trace correlation identity propagated through host execution and audit paths. */
  traceId?: string
  
/** Optional host/provider metadata; callers remain responsible for sensitive content and validation. */
  metadata?: Readonly<Record<string, unknown>>
}

/**
 * Audit input augmented with generated identity, timestamp and hash-chain links.
 * @see {@link issueApiKey}
 */
export interface PlatformAuditEvent extends PlatformAuditEventInput {
  
  /** Random UUID generated when the audit append is processed. */
  id: string
  
/** Event/effect occurrence timestamp; creation helpers normalize supported inputs to ISO text. */
  occurredAt: string
  
/** Previous audit event hash used to link ordered entries. */
  previousHash: string
  
  /** Content integrity digest; hashes are unkeyed and do not establish authorization or writer authenticity. */
  hash: string
}

const genesisHash = '0'.repeat(64)
function auditHash(event: Omit<PlatformAuditEvent, 'hash'>): string { return createHash('sha256').update(JSON.stringify(event), 'utf8').digest('hex') }

/**
 * Serialize audit events through a host sink and advance the local hash only after acceptance.
 * @remarks Requires node:crypto. Each instance starts at zero-hash genesis and has no persisted-head recovery API; host lifecycle must avoid presenting independent instances as one continuous chain. A rejected sink may have partially committed; deduplication/reconciliation belong to the host.
 *
 * @example
 * ```typescript
 * import { DurableAuditTrail } from "@alneas/eaos-core/security/platform-security";
 * import type { AuditSink } from "@alneas/eaos-core/security/audit-sink";
 * import type { PlatformAuditEvent } from "@alneas/eaos-core/security/platform-security";
 * async function appendHostEvent(sink: AuditSink<PlatformAuditEvent>) {
 *  const trail = new DurableAuditTrail(sink);
 *  return trail.append({ tenantId: "tenant-demo", userId: "user-demo", action: "notes.preview", outcome: "success" });
 * }
 * ```
 */
export class DurableAuditTrail {
  private previousHash = genesisHash
  private tail: Promise<void> = Promise.resolve()
  /**
   * Initialize a new genesis-based audit append stream.
   * @param sink - Host durable append capability; awaited before advancing this instance hash.
   * @param clock - Optional timestamp callback invoked for each append; defaults to current Date.
   *
   * @example
   * ```typescript
   * import { DurableAuditTrail } from "@alneas/eaos-core/security/platform-security";
   * import type { AuditSink } from "@alneas/eaos-core/security/audit-sink";
   * import type { PlatformAuditEvent } from "@alneas/eaos-core/security/platform-security";
   * function createHostTrail(sink: AuditSink<PlatformAuditEvent>) { return new DurableAuditTrail(sink); }
   * ```
   */
  constructor(private readonly sink: AuditSink<PlatformAuditEvent>, private readonly clock: () => Date = () => new Date()) {}
  /**
   * Clone and append one hash-linked event after earlier queued appends settle.
   * @param input - Audit scope/action/outcome; copied before generated UUID, timestamp and previousHash are added.
   * @returns The appended event after sink acceptance; the sink receives a separate structured clone.
   * @throws Rejects on cloning/serialization/date failures or propagated sink rejection.
   * @remarks A failure does not stop subsequent queued appends. No cancellation or retry is implemented; a rejected host write can have an uncertain durable outcome.
   * @example
   * ```typescript
   * import { DurableAuditTrail } from "@alneas/eaos-core/security/platform-security";
   * import type { AuditSink } from "@alneas/eaos-core/security/audit-sink";
   * import type { PlatformAuditEvent } from "@alneas/eaos-core/security/platform-security";
   * async function appendHostEvent(sink: AuditSink<PlatformAuditEvent>) {
   *  const trail = new DurableAuditTrail(sink);
   *  return trail.append({ tenantId: "tenant-demo", userId: "user-demo", action: "notes.preview", outcome: "success" });
   * }
   * ```
   */
  append(input: PlatformAuditEventInput): Promise<PlatformAuditEvent> {
    let result: PlatformAuditEvent | undefined
    const operation = this.tail.then(async () => {
      const eventWithoutHash: Omit<PlatformAuditEvent, 'hash'> = { ...structuredClone(input), id: randomUUID(), occurredAt: this.clock().toISOString(), previousHash: this.previousHash }
      const event = { ...eventWithoutHash, hash: auditHash(eventWithoutHash) }
      await this.sink.append(structuredClone(event))
      this.previousHash = event.hash
      result = event
    })
    this.tail = operation.catch(() => undefined)
    return operation.then(() => result!)
  }
}

/**
 * Verify an ordered audit chain starting from the zero-hash genesis.
 * @param events - Full chain in append order, starting at genesis rather than an arbitrary suffix.
 * @returns True when previousHash links and JSON-based event hashes all match; an empty chain is valid.
 * @throws JSON serialization errors for data that cannot be encoded.
 * @remarks Requires node:crypto. Unkeyed hashes do not authenticate the writer or detect a rewritten complete history without an externally trusted anchor.
 * @example
 * ```typescript
 * import { verifyAuditChain } from "@alneas/eaos-core/security/platform-security";
 * console.log(verifyAuditChain([])); // true
 * ```
 */
export function verifyAuditChain(events: readonly PlatformAuditEvent[]): boolean {
  let previousHash = genesisHash
  for (const event of events) {
    const { hash, ...eventWithoutHash } = event
    if (event.previousHash !== previousHash || auditHash(eventWithoutHash) !== hash) return false
    previousHash = hash
  }
  return true
}

/**
 * Tenant/user consent grant for a versioned purpose with optional expiry or revocation.
 * @see {@link issueApiKey}
 */
export interface ConsentRecord {
  
/** Verified tenant boundary for the record or operation; host authorization must establish this scope. */
  tenantId: string
  
/** User identity within the tenant supplied by the trusted host. */
  userId: string
  
  /** Named consent or agent-task purpose used by host policy evaluation. */
  purpose: string
  
  /** Consent text/purpose revision accepted by the user. */
  version: string
  
/** Parseable timestamp when consent begins; future grants do not count as active. */
  grantedAt: string
  
/** Optional absolute expiry; the owning validation/evaluation API determines whether it remains live. */
  expiresAt?: string | null
  
/** Revocation timestamp when present; an active value disables use. */
  revokedAt?: string | null
}

/**
 * Find a matching consent that has started, remains unrevoked and has not expired.
 * @param records - Host-supplied consent records; any qualifying match is sufficient.
 * @param requirement - Exact tenant/user/purpose and optional version; omitted now uses current Date and absent/falsy version accepts any version.
 * @returns Whether at least one active record matches.
 * @remarks Does not persist consent or establish that records came from a trusted source.
 * @example
 * ```typescript
 * import { hasActiveConsent } from "@alneas/eaos-core/security/platform-security";
 * const records = [{ tenantId: "tenant-demo", userId: "user-demo", purpose: "summarization", version: "1", grantedAt: "2026-01-01T00:00:00Z" }];
 * const requirement = { tenantId: "tenant-demo", userId: "user-demo", purpose: "summarization", version: "1", now: new Date("2026-10-19T00:00:00Z") };
 * console.log(hasActiveConsent(records, requirement)); // true
 * ```
 */
export function hasActiveConsent(records: readonly ConsentRecord[], requirement: { 
  /**
   * Exact trusted tenant identity to match against consent records.
   */
  tenantId: string; 
  /**
   * Exact authenticated user identity whose grant must match within the tenant.
   */
  userId: string; 
  /**
   * Exact consent purpose identifier; a grant for another purpose does not satisfy this requirement.
   */
  purpose: string; 
  /**
   * Optional exact consent revision; omission or an empty string accepts any recorded version.
   */
  version?: string; 
  /**
   * Optional evaluation clock for grant-start/expiry checks; omission uses current Date. A matching record must be granted at or before this instant and unrevoked/unexpired.
   */
  now?: Date }): boolean {
  const now = (requirement.now ?? new Date()).getTime()
  return records.some(record => record.tenantId === requirement.tenantId && record.userId === requirement.userId && record.purpose === requirement.purpose && (!requirement.version || record.version === requirement.version) && !record.revokedAt && Number.isFinite(Date.parse(record.grantedAt)) && Date.parse(record.grantedAt) <= now && (!record.expiresAt || (Number.isFinite(Date.parse(record.expiresAt)) && Date.parse(record.expiresAt) > now)))
}

/**
 * Require an active consent matching a tenant, user and purpose.
 * @param records - Trusted consent records passed to hasActiveConsent.
 * @param requirement - Required scope/version and optional evaluation clock; omitted now uses current Date.
 * @returns No value; successful completion means a matching consent exists.
 * @throws Error when no active consent satisfies the requirement.
 * @example
 * ```typescript
 * import { assertActiveConsent } from "@alneas/eaos-core/security/platform-security";
 * const records = [{ tenantId: "tenant-demo", userId: "user-demo", purpose: "summarization", version: "1", grantedAt: "2026-01-01T00:00:00Z" }];
 * const requirement = { tenantId: "tenant-demo", userId: "user-demo", purpose: "summarization", version: "1", now: new Date("2026-10-19T00:00:00Z") };
 * assertActiveConsent(records, requirement);
 * ```
 */
export function assertActiveConsent(records: readonly ConsentRecord[], requirement: { 
  /**
   * Exact trusted tenant identity to match against consent records.
   */
  tenantId: string; 
  /**
   * Exact authenticated user identity whose grant must match within the tenant.
   */
  userId: string; 
  /**
   * Exact consent purpose identifier; a grant for another purpose does not satisfy this requirement.
   */
  purpose: string; 
  /**
   * Optional exact consent revision; omission or an empty string accepts any recorded version.
   */
  version?: string; 
  /**
   * Optional evaluation clock for grant-start/expiry checks; omission uses current Date. A matching record must be granted at or before this instant and unrevoked/unexpired.
   */
  now?: Date }): void {
  if (!hasActiveConsent(records, requirement)) throw new Error(`Active consent required for ${requirement.purpose}`)
}
