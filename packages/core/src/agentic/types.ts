/**
 * Agent organization, routing and legacy execution metadata contracts.
 */

/**
 * Model capability/cost tiers used by built-in agentic routing metadata.
 * @see {@link ModelRoutingGateway}
 */
export type ModelTier = 'tier1_cloud_premium' | 'tier2_edge_local' | 'tier3_embedding_rerank'

/**
 * Prompt data classification used by heuristic sanitization and routing.
 * @see {@link ModelRoutingGateway}
 */
export type DataSensitivityLevel =
  | 'level1_public'     // 公開・一般的データ (Tier 1 クラウドモデル全開OK)
  | 'level2_internal'   // 社内一般データ (学習不可保証の商用モデル限定)
  | 'level3_strict'     // 機密・PII個人情報含む (OCI 2B/ローカルモデル強制 & マスキング)

/**
 * CLI bridge identifiers recognized by sandbox execution options.
 * @see {@link ModelRoutingGateway}
 */
export type ExecutionCliType = 'antigravity' | 'codex' | 'claude' | 'opencode' | 'goose' | 'hermes_agent'

/**
 * Static provider/model route metadata and declared sensitivity limits.
 * @see {@link ModelRoutingGateway}
 */
export interface ModelRoutingConfig {
  
  /** Provider identity from model metadata, travel discovery or connection/circuit health. */
  provider:
    | 'groq'
    | 'cloudflare_workers_ai'
    | 'mlx_local'
    | 'opencode'
    | 'google_ai_studio'
    | 'oci_local_2b'
    | 'ruri_embedding'
  
/** Provider-specific model name from the static routing catalog. */
  modelName: string
  
  /** Commercial entitlement category or model resource tier, interpreted by its owning policy. */
  tier: ModelTier
  
/** Declared no-training policy requirement; the host must verify and enforce the provider agreement. */
  requiresNoTraining: boolean
  
/** Data classifications the host advertises as permitted on this model/route. */
  allowedSensitivity: DataSensitivityLevel[]
}

/**
 * Original and masked prompt plus detected patterns and recommended model tier.
 * @see {@link ModelRoutingGateway}
 */
export interface SanitizationResult {
  
/** Unmodified prompt retained for caller use; may contain sensitive data. */
  originalPrompt: string
  
/** Prompt after recognized phone/email pattern replacement; detection is heuristic and incomplete. */
  sanitizedPrompt: string
  
/** Names of phone/email patterns recognized by the heuristic scanner. */
  detectedPiiTypes: string[]
  
/** Classification used by the host to constrain eligible execution routes. */
  sensitivityLevel: DataSensitivityLevel
  
/** Original sensitive text mapped to generated placeholders; protect this map as sensitive data. */
  appliedMaskings: Record<string, string> // e.g. { "山田太郎": "[NAME_001]" }
  
/** Model tier suggested by heuristic classification; not a provider-policy guarantee. */
  recommendedTier: ModelTier
}

/**
 * Organizational agent identity, reporting relationship, budget and lifecycle metadata.
 * @see {@link ModelRoutingGateway}
 */
export interface AgentNode {
  
  /** Organizational agent identity used for assignment and hierarchy. */
  id: string
  
  /** Organization identity grouping agents/tasks within host data. */
  orgId: string
  
/** Optional parent agent identity in the organizational reporting tree. */
  parentId?: string
  
  /** Human-readable display name supplied by the plugin/provider catalog; distinct from the stable ID. */
  name: string
  
  
  /** Organizational role used by host coordination: ceo, executive, manager, worker or red_team. */
  role: 'ceo' | 'executive' | 'manager' | 'worker' | 'red_team'
  
  /** Advertised agent model capability/cost tier; host routing applies actual policy. */
  tierLevel: ModelTier
  
/** Highest/declared sensitivity classification accepted by this agent according to host policy. */
  allowedSensitivityLevel: DataSensitivityLevel
  
/** Maximum advertised daily spending allowance in US dollars; accounting/enforcement belongs to the host. */
  dailyBudgetCapUsd: number
  
/** Host-reported spending already accrued today in US dollars. */
  currentDailySpendUsd: number
  
/** Advertised operation/capability names; presence alone does not authorize execution. */
  capabilities: string[]
  
  /** Host agent availability state; Core does not schedule work from this field. */
  status: 'active' | 'busy' | 'paused' | 'error'
  
/** Creation timestamp supplied or generated by the owning API. */
  createdAt: string
  
/** Timestamp of the latest host-recorded update; this contract does not persist changes. */
  updatedAt: string
}

/**
 * Shared human/AI task record with assignment, sensitivity and cost tracking.
 * @see {@link ModelRoutingGateway}
 */
export interface UnifiedTask {
  
  /** Host task-board identity shared by human/AI task handling. */
  id: string
  
/** Optional parent task identity for task decomposition. */
  parentTaskId?: string
  
  /** Organization identity grouping agents/tasks within host data. */
  orgId: string
  
  /** Human-readable draft, task, file or event title displayed by the host. */
  title: string
  
  /** Human-readable metadata describing the capability, workflow node or requirement to host users. */
  description: string
  
/** Whether this task is assigned to a human or AI agent. */
  assignedType: 'HUMAN' | 'AI'
  
/** Optional assigned agent identity when assignedType is AI. */
  assignedAgentId?: string
  
/** Optional assigned user identity when assignedType is HUMAN. */
  assignedUserId?: string
  
/** Host scheduling priority; execution broker candidate priority uses a signed safe-integer score boost. */
  priority: 'low' | 'medium' | 'high' | 'critical'
  
  /** Host task-board lifecycle, including pending approval and terminal outcomes. */
  status: 'backlog' | 'in_progress' | 'pending_approval' | 'completed' | 'failed'
  
/** Classification used by the host to constrain eligible execution routes. */
  sensitivityLevel: DataSensitivityLevel
  
/** Optional task spending ceiling in US dollars enforced by the host. */
  budgetCapUsd?: number
  
/** Host-reported cost accumulated for this task in US dollars. */
  currentCostUsd: number
  
/** Optional task due-date metadata interpreted by the host scheduler. */
  dueDate?: string
  
/** Creation timestamp supplied or generated by the owning API. */
  createdAt: string
  
/** Timestamp of the latest host-recorded update; this contract does not persist changes. */
  updatedAt: string
}

/**
 * Multi-agent discussion participants, rounds and convergence settings.
 * @see {@link ModelRoutingGateway}
 */
export interface DiscussionSession {
  
  /** Host identity of the multi-agent discussion session. */
  id: string
  
  /** Task identity correlating the agent/runtime operation with its owning workflow or task board. */
  taskId: string
  
  /** Exact event dispatch key used to locate a registered host handler. */
  topic: string
  
/** Agent records taking part in the discussion. */
  participants: AgentNode[]
  
/** Discussion contributions in stored order. */
  rounds: DiscussionRound[]
  
  /** Host discussion progress/convergence outcome. */
  status: 'active' | 'converged' | 'max_turns_reached' | 'escalated'
  
/** Host-configured discussion turn cap; Core types do not enforce it. */
  maxTurns: number
  
/** Convergence threshold conventionally from zero to one; host discussion logic enforces it. */
  similarityThreshold: number // 収束判定閾値 (0.0 ~ 1.0)
  
/** Optional host-approved discussion conclusion. */
  finalSummary?: string
}

/**
 * One participant contribution and optional similarity measurement.
 * @see {@link ModelRoutingGateway}
 */
export interface DiscussionRound {
  
/** Position of the contribution in the discussion sequence. */
  roundNumber: number
  
  /** Agent identity associated with the session, execution or assignment. */
  agentId: string
  
/** Display name of the contributing agent. */
  agentName: string
  
  
  /** Role label reported for this discussion contribution. */
  role: string
  
  /** Loaded skill instructions, model response text or proposed file content; treat external text as untrusted input. */
  content: string
  
/** Whether this contribution represents an adversarial/review perspective. */
  isRedTeamReview: boolean
  
/** Optional host-computed similarity to the previous contribution. */
  similarityScoreWithPrevious?: number
  
  
  /** Host-recorded timestamp for this discussion contribution. */
  timestamp: string
}

/**
 * Script and execution metadata passed to the sandbox/desktop bridge.
 * @see {@link ModelRoutingGateway}
 */
export interface SandboxExecutionRequest {
  
  /** Task identity correlating the agent/runtime operation with its owning workflow or task board. */
  taskId: string
  
  /** Agent identity associated with the session, execution or assignment. */
  agentId: string
  
/** Declared source language for sandbox metadata; simulated container mode does not execute it. */
  language: 'python' | 'bash' | 'javascript'
  
  
  /** Script/prompt source sent to the selected bridge; docker_cloud only simulates processing and Tauri passes this as its CLI prompt. */
  code: string
  
/** Optional requested execution bindings; the legacy sandbox does not apply them. */
  environmentVariables?: Record<string, string>
  
/** Optional execution deadline in milliseconds; enforcement belongs to the API/runtime consuming this metadata. */
  timeoutMs?: number
}

/**
 * Reported execution identity, exit code, streams and elapsed time.
 * @see {@link ModelRoutingGateway}
 */
export interface SandboxExecutionResult {
  
  /** Host/provider execution identity; the legacy sandbox may generate this for a simulated result. */
  executionId: string
  
/** Reported process exit code; zero may be simulated by the legacy sandbox. */
  exitCode: number
  
/** Reported standard output text; the legacy sandbox may synthesize it. */
  stdout: string
  
/** Reported standard error text. */
  stderr: string
  
/** Reported elapsed execution time in milliseconds; it may describe simulated execution for the legacy sandbox. */
  executionTimeMs: number
  
/** Optional human-readable failure detail; absence does not independently establish success. */
  error?: string
}
