/**
 * Instinct Extraction & Continuous Learning Engine
 * Converts session trajectories into reusable instincts indexed via the provider-neutral VectorSearchAdapter.
 */

import type { VectorSearchAdapter } from '../vector/index'

/**
 * Tenant/domain heuristic learned from a session with confidence and outcome counts.
 * @see {@link InstinctEngine}
 */
export interface AgentInstinct {
  
  /** Generated process-local heuristic identity; extraction does not persist it. */
  id: string
  
/** Verified tenant boundary for the record or operation; host authorization must establish this scope. */
  tenantId: string
  
  
  /** Exact host classification key used by local heuristic filtering. */
  domain: string
  
  /**
   * Observed session pattern that motivates the reusable heuristic.
   */
  pattern: string
  
/** Reusable suggested handling text extracted or synthesized from a session. */
  heuristic: string
  
/** Reported confidence ratio, conventionally from zero to one; validate at the consuming boundary. */
  confidence: number // 0.0 ~ 1.0
  
/** Number of successful uses reported for the heuristic. */
  successCount: number
  
/** Number of failed uses reported for the heuristic. */
  failureCount: number
  
/** Optional numeric embedding metadata; extraction does not generate or persist embeddings. */
  embedding?: number[]
  
/** Creation timestamp supplied or generated by the owning API. */
  createdAt: string
  
/** Timestamp of the latest host-recorded update; this contract does not persist changes. */
  updatedAt: string
}

/**
 * Keep session-derived heuristics locally and optionally read a host vector index.
 * @remarks Extraction stores only process-local references and does not embed or index them. Vector search results are mapped from host metadata without an additional tenant-result validator; the adapter must enforce tenant scope. Search failures log a warning and fall back to local filtering.
 *
 * @example
 * ```typescript
 * import { InstinctEngine } from "@alneas/eaos-core/agentic/instinct-engine";
 * const engine = new InstinctEngine();
 * console.log(await engine.findRelevantInstincts({ tenantId: "tenant-demo", domain: "notes" })); // []
 * ```
 */
export class InstinctEngine {
  private localInstincts: AgentInstinct[] = []

  /**
   * Initialize local heuristic storage and optional vector search.
   * @param vectorAdapter - Trusted host search adapter; omitted means local lookup only.
   *
   * @example
   * ```typescript
   * import { InstinctEngine } from "@alneas/eaos-core/agentic/instinct-engine";
   * const engine = new InstinctEngine();
   * console.log(await engine.findRelevantInstincts({ tenantId: "tenant-demo", domain: "notes" }));
   * ```
   */
  constructor(private vectorAdapter?: VectorSearchAdapter) {}

  /**
   * Extract or synthesize one heuristic from a successful multi-turn session.
   * @param params - Tenant/domain and history; returns null for unsuccessful sessions or fewer than two turns. Optional extractFn receives history and resolves pattern/heuristic/confidence; failures log a warning and use built-in defaults.
   * @returns A newly stored local instinct reference, or null. Default confidence is 0.85 with one success and zero failures.
   * @remarks No embedding/index write, output validation or durable persistence occurs. The caller must handle sensitive trajectory content and validate extractor output.
   * @example
   * ```typescript
   * import { InstinctEngine } from "@alneas/eaos-core/agentic/instinct-engine";
   * const engine = new InstinctEngine();
   * console.log(await engine.extractInstinctsFromSession({ tenantId: "tenant-demo", domain: "notes", success: true, history: [{ role: "user", content: "Preview notes" }, { role: "assistant", content: "No changes" }] }));
   * ```
   */
  async extractInstinctsFromSession(params: {
    
/** Verified tenant boundary for the record or operation; host authorization must establish this scope. */
    tenantId: string
    
    
  /** Classification key copied to the extracted local heuristic. */
  domain: string
    
    /** Session turns supplied for lifecycle/extraction; sensitive content handling remains host-owned. */
    history: Array<{ 
  
  /** Host conversation-speaker label associated with this history turn. */
  role: string; 
  /** Loaded skill instructions, model response text or proposed file content; treat external text as untrusted input. */
  content: string }>
    
    /** Reported completion flag; inspect status/receipt and reconcile any uncertain side effects before retrying. */
    success: boolean
    
  /**
   * Extract a proposed heuristic from successful session history.
   * @param history - Original session turns passed by reference after success and minimum-length checks.
   * @returns Proposed pattern, heuristic and confidence; the engine uses them without domain/range validation.
   * @throws Callback rejections are caught/logged by extraction, which retains its default heuristic.
   * @remarks Host owns provider access and sensitive-history handling; this callback does not write a vector index.
   * @see {@link InstinctEngine.extractInstinctsFromSession}
   *
   * @example
   * ```typescript
   * import type { InstinctEngine } from "@alneas/eaos-core/agentic/instinct-engine";
   * async function extractWithHost(params: Parameters<InstinctEngine["extractInstinctsFromSession"]>[0]) {
   *  if (!params.extractFn) throw new Error("Configure a host extractor");
   *  return params.extractFn(params.history);
   * }
   * ```
   */
  extractFn?: (history: Array<{ 
  
  /** Host conversation-speaker label associated with this history turn. */
  role: string; 
  /** Loaded skill instructions, model response text or proposed file content; treat external text as untrusted input. */
  content: string }>) => Promise<{ 
  /**
   * Host-extracted session pattern; the engine accepts it without shape/range validation.
   */
  pattern: string; 
/** Reusable suggested handling text extracted or synthesized from a session. */
  heuristic: string; 
/** Reported confidence ratio, conventionally from zero to one; validate at the consuming boundary. */
  confidence: number }>
  }): Promise<AgentInstinct | null> {
    if (!params.success || params.history.length < 2) {
      return null
    }

    let pattern = `Session completed with ${params.history.length} turns`
    let heuristic = 'Standard resolution path'
    let confidence = 0.85

    if (params.extractFn) {
      try {
        const extracted = await params.extractFn(params.history)
        pattern = extracted.pattern
        heuristic = extracted.heuristic
        confidence = extracted.confidence
      } catch (err) {
        console.warn(`[InstinctEngine] LLM extraction error: ${(err as Error).message}`)
      }
    }

    const instinct: AgentInstinct = {
      id: `instinct_${Date.now()}_${Math.random().toString(36).substr(2, 6)}`,
      tenantId: params.tenantId,
      domain: params.domain,
      pattern,
      heuristic,
      confidence,
      successCount: 1,
      failureCount: 0,
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    }

    this.localInstincts.push(instinct)
    return instinct
  }

  /**
   * Read vector-index matches when configured, otherwise filter local heuristics.
   * @param options - Tenant/domain and optional query vector/topK. topK defaults to 5; vector queries use indexId ai-instincts and do not include a domain filter.
   * @returns Mapped provider results, or original local references filtered by exact tenant/domain in insertion order.
   * @remarks Provider errors are logged and fall back locally. The adapter is trusted for result tenant scope and score/metadata validity; no cancellation/retry is supplied.
   * @example
   * ```typescript
   * import { InstinctEngine } from "@alneas/eaos-core/agentic/instinct-engine";
   * const engine = new InstinctEngine();
   * console.log(await engine.findRelevantInstincts({ tenantId: "tenant-demo", domain: "notes", topK: 5 }));
   * ```
   */
  async findRelevantInstincts(options: {
    
/** Verified tenant boundary for the record or operation; host authorization must establish this scope. */
    tenantId: string
    
    
  /** Exact domain filter for local fallback; vector search does not send this as a filter. */
  domain: string
    
/** Nonempty finite numeric embedding; the host checks its dimension against the selected index. */
    queryVector?: number[]
    
/** Requested maximum result count; vector request validation permits integers from 1 to 10000. */
    topK?: number
  }): Promise<AgentInstinct[]> {
    if (this.vectorAdapter && options.queryVector && options.queryVector.length > 0) {
      try {
        const vectorResults = await this.vectorAdapter.search({
          tenantId: options.tenantId,
          indexId: 'ai-instincts',
          queryVector: options.queryVector,
          topK: options.topK ?? 5,
        })
        return vectorResults.map(hit => ({
          id: hit.id,
          tenantId: hit.tenantId,
          domain: typeof hit.metadata?.domain === 'string' ? hit.metadata.domain : options.domain,
          pattern: typeof hit.metadata?.pattern === 'string' ? hit.metadata.pattern : '',
          heuristic: typeof hit.metadata?.heuristic === 'string' ? hit.metadata.heuristic : '',
          confidence: typeof hit.metadata?.confidence === 'number' ? hit.metadata.confidence : hit.score,
          successCount: typeof hit.metadata?.successCount === 'number' ? hit.metadata.successCount : 0,
          failureCount: typeof hit.metadata?.failureCount === 'number' ? hit.metadata.failureCount : 0,
          embedding: Array.isArray(hit.metadata?.embedding) ? hit.metadata.embedding.filter((value): value is number => typeof value === 'number') : undefined,
          createdAt: typeof hit.metadata?.createdAt === 'string' ? hit.metadata.createdAt : new Date(0).toISOString(),
          updatedAt: typeof hit.metadata?.updatedAt === 'string' ? hit.metadata.updatedAt : new Date(0).toISOString(),
        }))
      } catch (err) {
        console.warn(`[InstinctEngine] Vector search fallback: ${(err as Error).message}`)
      }
    }

    return this.localInstincts
      .filter((i) => i.tenantId === options.tenantId && i.domain === options.domain)
      .slice(0, options.topK ?? 5)
  }
}

/**
 * Module-local in-memory instinct engine without a configured vector provider.
 * @see {@link InstinctEngine}
 */
export const globalInstinctEngine = new InstinctEngine()
