import {createHash,randomUUID} from 'node:crypto'
import {mkdir,readFile,rename,rm,writeFile} from 'node:fs/promises'
import {dirname} from 'node:path'
import {safePath} from './files'

const hash=(text:string)=>createHash('sha256').update(text).digest('hex')
const prefix='// Generated by EAOS feature registrations; sha256:'
const owned=(text:string)=>{const newline=text.indexOf('\n');return text.slice(0,newline)===prefix+hash(text.slice(newline+1))}
const read=async(path:string)=>readFile(path,'utf8').catch(error=>{if(error.code!=='ENOENT')throw error;return null})

// Internal transaction seam allows deterministic failure tests without global mocks.
export async function writeGeneratedFiles(root:string,files:readonly {path:string;text:string}[],check=false,io:{rename:typeof rename}={rename}):Promise<void>{
 const lock=await safePath(root,'.eaos/feature-register.lock')
 const entries=await Promise.all(files.map(async file=>({relative:file.path,path:await safePath(root,file.path),text:prefix+hash(file.text)+'\n'+file.text})))
 const paths=[...entries.map(file=>file.path),lock]
 if(new Set(paths).size!==paths.length||paths.some((path,index)=>paths.some((other,otherIndex)=>index!==otherIndex&&other.startsWith(path+'/'))))throw Error('Generated feature outputs must be distinct from each other and the lock, without ancestor paths')
 if(check){for(const file of entries)if(await read(file.path)!==file.text)throw Error('Stale generated feature output: '+file.path);return}
 await mkdir(dirname(lock),{recursive:true})
 // A failed exclusive acquisition must not enter cleanup or touch another writer.
 await writeFile(lock,randomUUID(),{flag:'wx'})
 const previous=new Map<string,string|null>(),staged=new Map<string,string>(),replaced:typeof entries=[]
 try{
  for(const file of entries){
   const value=await read(file.path)
   if(value!==null&&!owned(value))throw Error('Unmanaged or edited generated feature output: '+file.path)
   previous.set(file.path,value)
  }
  for(const file of entries){
   await mkdir(dirname(file.path),{recursive:true})
   const temporary=file.path+'.new-'+randomUUID();staged.set(file.path,temporary)
   await writeFile(temporary,file.text,{flag:'wx'})
  }
  for(const file of entries){
   await safePath(root,file.relative)
   if(await read(file.path)!==previous.get(file.path))throw Error('Concurrent edited generated feature output: '+file.path)
   await io.rename(staged.get(file.path)!,file.path);replaced.push(file)
  }
 }catch(error){
  for(const file of replaced.reverse()){
   // Preserve an external edit made after our replacement; never roll it back.
   if(await read(file.path)!==file.text)continue
   const value=previous.get(file.path)!
   if(value===null)await rm(file.path,{force:true})
   else await writeFile(file.path,value)
  }
  throw error
 }finally{
  for(const temporary of staged.values())await rm(temporary,{force:true})
  await rm(lock)
 }
}
