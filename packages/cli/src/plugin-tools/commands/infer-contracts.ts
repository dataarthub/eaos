import fs from 'node:fs'
import path from 'node:path'
import { CommandOptions, findPluginDir, pascalCase, writeDraft } from '../utils'

/**
 * Infer a draft service interface from asynchronous source-method signatures.
 * @param workspaceRoot - Trusted workspace containing the plugin.
 * @param options - plugin is required; check compares and write permits replacement of the generated draft.
 * @returns Resolves without a value after writing/checking, or skips when the services directory is absent.
 * @throws Rejects invalid plugin selection, protected/stale drafts or filesystem errors.
 * @remarks Pattern matching does not prove runtime contracts; review nested types and implementation semantics before adopting the interface.
 * @example
 * import { inferContracts } from '@alneas/eaos-cli/plugin-tools'
 * export async function checkInferred(root: string) { await inferContracts(root, { plugin: 'notes', check: true }) }
 */
export async function inferContracts(workspaceRoot: string, options: CommandOptions): Promise<void> {
  const pluginId = options.plugin
  if (!pluginId) {
    throw new Error('--plugin <plugin-id> is required for infer-contracts')
  }

  const pluginDir = findPluginDir(workspaceRoot, pluginId)
  const servicesDir = path.join(pluginDir, 'src', 'services')
  const contractsPath = path.join(pluginDir, 'src', 'contracts', 'inferred.generated.ts')

  if (!fs.existsSync(servicesDir)) {
    console.log(`ℹ️ [infer-contracts] No src/services found in plugin '${pluginId}'. Skipping.`)
    return
  }

  const interfaceMethods: string[] = []

  const files = fs.readdirSync(servicesDir).filter((f) => f.endsWith('.ts'))
  for (const file of files) {
    const filePath = path.join(servicesDir, file)
    const content = fs.readFileSync(filePath, 'utf-8')
    const matches = content.matchAll(/async\s+([A-Za-z0-9_]+)\s*\(([^)]*)\)\s*:\s*Promise<([^>]+)>/g)
    for (const m of matches) {
      if (!m[1].startsWith('_')) {
        interfaceMethods.push(`  ${m[1]}(${m[2]}): Promise<${m[3]}>`)
      }
    }
  }

  const pascalId = pascalCase(pluginId)
  const contractCode = `// Auto-generated by @alneas/eaos-cli plugin infer-contracts

export interface I${pascalId}Service {
${interfaceMethods.length > 0 ? interfaceMethods.join('\n') : '  // Add service contract signatures here'}
}
`

  const contractsDir = path.dirname(contractsPath)
  if (!fs.existsSync(contractsDir)) {
    fs.mkdirSync(contractsDir, { recursive: true })
  }

  writeDraft(contractsPath, contractCode, options)
  console.log(`✨ [infer-contracts] Inferred contract interface I${pascalId}Service at ${contractsPath}`)
}
