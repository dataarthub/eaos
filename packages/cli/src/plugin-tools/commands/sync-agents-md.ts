import fs from 'node:fs'
import path from 'node:path'
import { type CommandOptions, findPluginDir } from '../utils'
import { inspectPlugin, type PluginInspection } from '../inspect'

/**
 * Opening marker delimiting the single CLI-owned plugin contract block inside AGENTS.md.
 * @see {@link agentDocumentNext} for the canonical usage example and runtime requirements.
 */
export const generatedStart = '<!-- eaos:generated:start -->'
/**
 * Closing marker delimiting the single CLI-owned plugin contract block inside AGENTS.md.
 * @see {@link agentDocumentNext} for the canonical usage example and runtime requirements.
 */
export const generatedEnd = '<!-- eaos:generated:end -->'
/**
 * Serialize inspected contract metadata into a delimited generated AGENTS block.
 * @param info - Reviewed source-inspection result; issues are omitted from serialized contract metadata.
 * @returns Markdown with exact generated block markers and a JSON contract payload.
 * @throws JSON serialization failures propagate.
 * @remarks Serialization alone does not reject unresolved issues or validate runtime authorization.
 * @example
 * import { renderAgentMetadata } from '@alneas/eaos-cli/plugin-tools'
 * import { inspectPlugin } from '@alneas/eaos-cli/plugin-tools/inspect'
 * export function metadata(root: string) { return renderAgentMetadata(inspectPlugin(root, 'notes')) }
 */
export function renderAgentMetadata(info: PluginInspection): string {
 const { issues: _, ...contract } = info
 return `${generatedStart}\n## Generated plugin contract\n\nGenerated by eaos plugin sync-agents. Source declarations are authoritative.\nArgument schema hashes detect source drift; they do not validate runtime authorization.\n\n\`\`\`json\n${JSON.stringify(contract, null, 2)}\n\`\`\`\n${generatedEnd}`
}
/**
 * Replace one well-formed generated block while preserving surrounding human-authored text.
 * @param existing - Current document text, possibly without a generated block.
 * @param block - Replacement generated block, normally from renderAgentMetadata.
 * @returns Updated document text; a missing block is appended.
 * @throws If existing markers are mismatched, repeated or reversed.
 * @remarks The replacement block itself is trusted and is not parsed for marker validity.
 * @example
 * import { agentDocumentNext } from '@alneas/eaos-cli/plugin-tools'
 * const next = agentDocumentNext('# Notes', '<!-- eaos:generated:start -->\nContract\n<!-- eaos:generated:end -->')
 */
export function agentDocumentNext(existing: string, block: string): string {
 const starts = existing.split(generatedStart).length - 1, ends = existing.split(generatedEnd).length - 1
 const begin = existing.indexOf(generatedStart), finish = existing.indexOf(generatedEnd)
 if (starts !== ends || starts > 1 || (starts && finish < begin)) throw new Error('Invalid generated block markers')
 return starts ? existing.slice(0, begin) + block + existing.slice(finish + generatedEnd.length) : existing + (existing ? '\n\n' : '') + block + '\n'
}
/**
 * Synchronize only the generated metadata block of a plugin AGENTS.md file.
 * @param root - Trusted workspace root.
 * @param options - plugin is required; check performs equality verification without writing.
 * @returns Resolves without a value when the document matches or has been updated.
 * @throws Rejects symlink documents, unresolved inspected contracts, malformed blocks, stale checks or filesystem failures.
 * @remarks Preserves text outside the generated block and does not alter unrelated agent instructions.
 * @example
 * import { syncAgentsMd } from '@alneas/eaos-cli/plugin-tools'
 * export async function checkAgents(root: string) { await syncAgentsMd(root, { plugin: 'notes', check: true }) }
 */
export async function syncAgentsMd(root: string, options: CommandOptions): Promise<void> {
 if (!options.plugin) throw new Error('--plugin <plugin-id> is required for sync-agents')
 const dir = findPluginDir(root, options.plugin), file = path.join(dir, 'AGENTS.md')
 if (fs.existsSync(file) && fs.lstatSync(file).isSymbolicLink()) throw new Error('Document symlinks are not supported')
 const info = inspectPlugin(root, options.plugin)
 if (info.issues.length) throw new Error(`Cannot sync unresolved contract: ${info.issues.map(i => `${i.code}: ${i.message}`).join('; ')}`)
 const existing = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : ''
 const next = agentDocumentNext(existing, renderAgentMetadata(info))
 if (options.check) { if (existing !== next) throw new Error(`AGENTS.md is out of sync: ${options.plugin}`) }
 else { fs.writeFileSync(file, next); console.log(`Updated generated metadata: ${options.plugin}`) }
}
